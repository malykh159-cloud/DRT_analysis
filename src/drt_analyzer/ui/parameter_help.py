class ParameterHelpDialog(QtW.QDialog):
    def __init__(self, key, parent=None):
        super().__init__(parent)
        title, definition, effect, advice = PARAMETER_HELP[key]
        self.setObjectName("parameter_help_"+key)
        self.setWindowTitle(title)
        self.resize(620, 460)
        layout = QtW.QVBoxLayout(self)
        self.text = QtW.QTextBrowser()
        sections = [("Что это", definition), ("На что влияет", effect), ("Практический выбор", advice)]
        reference = "docs/BAYESIAN_DRT.md" if key.startswith("bayesian_") else "docs/MATHEMATICS.md"
        self.text.setHtml("<h2>"+escape(title)+"</h2>"+"".join(
            f"<h3>{escape(heading)}</h3><p>{escape(content)}</p>" for heading, content in sections)
            +f"<p><small>Формулы и научные источники: {reference}</small></p>")
        layout.addWidget(self.text)
        buttons = QtW.QDialogButtonBox(QtW.QDialogButtonBox.StandardButton.Close)
        buttons.rejected.connect(self.close)
        layout.addWidget(buttons)


def help_button(key, parent):
    """Modeless help; no confirmation or interruption of editing."""
    button = QtW.QToolButton(parent)
    button.setText("?")
    button.setObjectName("help_"+key)
    button.setFixedSize(22, 22)
    button.setToolTip("Описание и выбор: "+PARAMETER_HELP[key][0])
    button.setAccessibleName("Справка: "+PARAMETER_HELP[key][0])
    def show():
        if not hasattr(button, "help_dialog"):
            button.help_dialog = ParameterHelpDialog(key, parent)
        button.help_dialog.show()
        button.help_dialog.raise_()
        button.help_dialog.activateWindow()
    button.clicked.connect(show)
    return button


def add_parameter(form, label, widget, key):
    row = QtW.QWidget()
    layout = QtW.QHBoxLayout(row)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(4)
    layout.addWidget(widget, 1)
    layout.addWidget(help_button(key, row))
    if label:
        form.addRow(label, row)
    else:
        form.addRow(row)
